#!/usr/bin/env python3
"""Writes src/msk144_generator.inc from WSJT-X 567ad29ce's
lib/ldpc_128_90_generator.f90 (the 38 rows of the (128,90) code's generator,
23 hex digits each, 90 bits, the last digit's two high bits).
Usage: msk144-generator-table.py GENERATOR.f90 > OUT.inc

The table is Joe Taylor, K1JT, Steven Franke, K9AN, and the WSJT-X team's
(GNU GPL v3), and so is this."""
import re, sys

text = open(sys.argv[1]).read()
m = re.search(r'data\s+g\s*/(.*?)/', text, re.S | re.I)
rows = re.findall(r'"([0-9a-fA-F]{23})"', m.group(1))
assert len(rows) == 38
print("// Generated by scripts/msk144-generator-table.py from WSJT-X 567ad29ce")
print("// lib/ldpc_128_90_generator.f90; do not edit.")
print("// Joe Taylor, K1JT, Steven Franke, K9AN, and the WSJT-X team (GNU GPL v3), and so is this.")
print("// g(1:38): row i of the generator, 23 hex digits, MSB first (the last digit's two high bits count).")
print("static const char* const kGen[38] = {")
for r in rows:
    print('    "%s",' % r)
print("};")
