#!/usr/bin/env python3
"""Writes src/msk40_tables.inc from WSJT-X 567ad29ce's lib/bpdecode40.f90
(colorder, Mn, Nm, nrw), in the Fortran's layout (column by column, 1-based).
Usage: msk40-tables.py bpdecode40.f90 > OUT.inc

The tables are Joe Taylor, K1JT, Steven Franke, K9AN, and the WSJT-X team's
(GNU GPL v3), and so is this."""
import re, sys

text = open(sys.argv[1]).read()
def data(name):
    m = re.search(r'data\s+%s\s*/(.*?)/' % name, text, re.S | re.I)
    return [int(x) for x in re.findall(r'-?\d+', m.group(1).replace('&', ''))]
Mn, Nm, co, nrw = data('Mn'), data('Nm'), data('colorder'), data('nrw')
assert (len(Mn), len(Nm), len(co), len(nrw)) == (3 * 32, 7 * 16, 32, 16)
print("// Generated by scripts/msk40-tables.py from WSJT-X 567ad29ce lib/bpdecode40.f90; do not edit.")
print("// Joe Taylor, K1JT, Steven Franke, K9AN, and the WSJT-X team (GNU GPL v3), and so is this.")
print("// Fortran's layout: Mn(3,32) and Nm(7,16) column by column, 1-based bit and check numbers")
print("// (0 past a check's nrw): kMn[j-1][kk-1], kNm[j-1][i-1].")
print("constexpr signed char kColorder[32] = {" + ", ".join(map(str, co)) + "};")
print("constexpr signed char kMn[32][3] = {")
for j in range(32): print("    {" + ", ".join(map(str, Mn[3 * j:3 * j + 3])) + "},")
print("};")
print("constexpr signed char kNm[16][7] = {")
for j in range(16): print("    {" + ", ".join(map(str, Nm[7 * j:7 * j + 7])) + "},")
print("};")
print("constexpr signed char kNrw[16] = {" + ", ".join(map(str, nrw)) + "};")
