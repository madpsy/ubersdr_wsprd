#!/usr/bin/env python3
"""Writes src/msk144_ldpc_tables.inc from WSJT-X 567ad29ce's
lib/ldpc_128_90_reordered_parity.f90 (Mn, Nm, nrw, ncw), in the Fortran's
layout (column by column, 1-based).  Usage: msk144-ldpc-tables.py PARITY.f90 > OUT.inc"""
import re, sys

text = open(sys.argv[1]).read()
def data(name):
    m = re.search(r'data\s+%s\s*/(.*?)/' % name, text, re.S | re.I)
    return [int(x) for x in re.findall(r'-?\d+', m.group(1))]
Mn, Nm, nrw = data('Mn'), data('Nm'), data('nrw')
assert (len(Mn), len(Nm), len(nrw)) == (3 * 128, 11 * 38, 38)
print("// Generated by scripts/msk144-ldpc-tables.py from WSJT-X 567ad29ce")
print("// lib/ldpc_128_90_reordered_parity.f90; do not edit.")
print("// Joe Taylor, K1JT, Steven Franke, K9AN, and the WSJT-X team (GNU GPL v3), and so is this.")
print("// Fortran's layout: Mn(3,128) and Nm(11,38) column by column, 1-based bit")
print("// and check numbers (0 past a check's nrw).")
print("static const int kNcw = 3;")
def table(name, vals, rows, cols):
    print("static const short %s[%d][%d] = {" % (name, cols, rows))
    for c in range(cols):
        print("    {" + ", ".join(str(v) for v in vals[c * rows:(c + 1) * rows]) + "},")
    print("};")
table("kMn", Mn, 3, 128)
table("kNm", Nm, 11, 38)
print("static const short kNrw[38] = {" + ", ".join(str(v) for v in nrw) + "};")
